-- Runs as SYS in the CDB root (SQL*Plus: no text after a semicolon on the same line).
-- Common user so it can read CDB-level AWR from the root.
CREATE USER C##DBTRIAGE IDENTIFIED BY dbtriage CONTAINER=ALL;
GRANT CREATE SESSION, SELECT_CATALOG_ROLE, SELECT ANY DICTIONARY TO C##DBTRIAGE CONTAINER=ALL;
-- Without this a common user sees only the root container (CON_ID 1) in V$ and DBA_HIST views
ALTER USER C##DBTRIAGE SET CONTAINER_DATA=ALL CONTAINER=CURRENT;
-- AWR report and create_snapshot
GRANT EXECUTE ON DBMS_WORKLOAD_REPOSITORY TO C##DBTRIAGE CONTAINER=ALL;
-- dbms_addm.get_report
GRANT ADVISOR TO C##DBTRIAGE CONTAINER=ALL;
GRANT EXECUTE ON DBMS_ADDM TO C##DBTRIAGE CONTAINER=ALL;

-- Sample schema for the load generator, in the PDB
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE USER app IDENTIFIED BY app QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO app;
CREATE TABLE app.orders (
  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, customer_id NUMBER NOT NULL, status VARCHAR2(16) NOT NULL,
  amount NUMBER(10,2) NOT NULL, created_at TIMESTAMP NOT NULL, note VARCHAR2(64)
);
CREATE INDEX app.orders_cust ON app.orders (customer_id);
INSERT INTO app.orders (customer_id, status, amount, created_at, note)
SELECT TRUNC(DBMS_RANDOM.VALUE(0, 5000)),
       CASE TRUNC(DBMS_RANDOM.VALUE(0, 4)) WHEN 0 THEN 'new' WHEN 1 THEN 'paid' WHEN 2 THEN 'shipped' ELSE 'cancelled' END,
       ROUND(DBMS_RANDOM.VALUE(0, 500), 2), SYSTIMESTAMP - NUMTODSINTERVAL(DBMS_RANDOM.VALUE(0, 90), 'DAY'),
       DBMS_RANDOM.STRING('x', 32)
FROM dual CONNECT BY LEVEL <= 200000;
COMMIT;
EXEC DBMS_STATS.GATHER_TABLE_STATS('APP', 'ORDERS');
